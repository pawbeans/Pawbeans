// inside the gut (navy): a river of food. Gut: calm, the walls soak water out (drops cross the wall). Too fast: it
// rushes, white water, the water stays in. Too slow: a sluggish, drier river, still soaking, cracks appear.
function tubePath() {
  const P = [];
  const run = (x0, x1, y) => { for (let i = 0; i <= 16; i++) P.push([lerp(x0, x1, i / 16), y]); };
  const bend = (cx, y0, y1, sd) => { for (let i = 1; i < 16; i++) { const a = -Math.PI / 2 + Math.PI * i / 16; P.push([cx + sd * Math.cos(a) * (y1 - y0) / 2, (y0 + y1) / 2 + Math.sin(a) * (y1 - y0) / 2]); } };
  P.push([-120, 640]); run(-60, 800, 640); bend(800, 640, 920, 1); run(800, 280, 920); bend(280, 920, 1200, -1); run(280, 900, 1200); P.push([1000, 1240], [1080, 1280]);
  return spline(P, false, 6);
}
const TUBE = tubePath(), TLEN = G.arclen(TUBE), TTOT = TLEN[TLEN.length - 1];
function tubeAt(s) { // point and unit normal at arclength s
  const pts = G.prefix(TUBE, clamp(s / TTOT, 0.001, 1)), q = pts[pts.length - 1], q0 = pts[Math.max(0, pts.length - 5)];
  const dx = q[0] - q0[0], dy = q[1] - q0[1], dl = Math.hypot(dx, dy) || 1;
  return { x: q[0], y: q[1], tx: dx / dl, ty: dy / dl, nx: -dy / dl, ny: dx / dl };
}
