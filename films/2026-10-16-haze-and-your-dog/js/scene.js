function stage(c, v, tq, a, b, o = {}) {
  drawPaper(c, W, H);
  const z = (o.z0 ?? 1) + (o.dz ?? 0.05) * E.io2(inv(a, b, tq));
  c.save(); cam(c, o.cx ?? 540, o.cy ?? 960, z);
  floor(c, v);
}
function popAt(c, x, y, sc, fn) { if (sc <= 0) return; c.save(); c.translate(x, y); c.scale(sc, sc); c.translate(-x, -y); fn(); c.restore(); }

