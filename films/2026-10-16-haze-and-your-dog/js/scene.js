// inside (navy): the airway from the nose to the lungs. Big bits of haze snag in the nose; the tiny ones slip past,
// rushing down the windpipe into the lungs (on 1s, smeared), and the lungs flush orange. Then EYES · NOSE · BREATHING.
const SPECKS = Array.from({ length: 14 }, (_, k) => ({ big: k % 3 === 0, d: hs(k, 9) * 0.5, off: (hs(k, 4) - 0.5) * 50, side: k % 2 ? 1 : -1 }));
function shotInside(c, t, f, D) {
  const v = bv(D), tq = D.fq / FPS;
  c.fillStyle = PAL.navy; c.fillRect(0, 0, W, H);
  c.save(); c.globalAlpha = 0.5; G.hatch(c, [[0, 0], [W, 0], [W, H], [0, H]], { seed: 800 + v, gap: 46, ang: -0.6, w: 2.4, amp: 2, color: PAL.navyDeep, cx: W / 2, cy: H / 2 }); c.restore();
  const push = 1 + 0.08 * E.io2(inv(6.5, 14.0, tq));
  c.save(); c.translate(540, 900); c.scale(push, push); c.translate(-540, -900); c.translate(0, 12 * Math.sin(tq * 0.8));
  const lg = E.io2(inv(MK('lungs') - 0.1, MK('lungs') + 0.3, tq));
  const tube = CA.airway(c, v, lg * (0.7 + 0.3 * Math.sin(tq * 6)));
  const TLn = G.arclen(tube), TT = TLn[TLn.length - 1];
  const at = (s) => { const pts = G.prefix(tube, clamp(s / TT, 0.001, 1)), q = pts[pts.length - 1], q0 = pts[Math.max(0, pts.length - 5)]; const dx = q[0] - q0[0], dy = q[1] - q0[1], l = Math.hypot(dx, dy) || 1; return { x: q[0], y: q[1], tx: dx / l, ty: dy / l, nx: -dy / l, ny: dx / l }; };
  const t0 = MK('tiny') - 0.2;
  SPECKS.forEach((S, k) => {
    // each speck enters from off the left edge into the nostril at its own time, on a loop
    const ph = ((tq - 6.5) * 0.35 + S.d + k / SPECKS.length) % 1;
    if (S.big) { // big bits drift in and stick among the nose hairs
      const u = Math.min(ph * 2.2, 1), x = lerp(-60, 180 + (k % 4) * 22, E.out2(u)), y = 570 + S.off * 0.8;
      CA.speck(c, x, y, 26, 900 + k, v); return;
    }
    if (tq < t0) { const x = lerp(-60, 140, ph), y = 570 + S.off * 0.6; CA.speck(c, x, y, 7, 900 + k, v); return; }
    // tiny ones rush down the airway on 1s, a smeared streak behind each, then scatter into a lung
    const u = (tq - t0) * 0.55 + ph * 0.6, along = u % 1.3;
    if (along < 1) {
      const P = at(along * TT), x = P.x + P.nx * S.off * 0.6, y = P.y + P.ny * S.off * 0.6, L = 50;
      inkStroke(c, [[x - P.tx * L, y - P.ty * L], [x, y]], { seed: 940 + k + f, w: 6, t0: 20, t1: 4, min: 0.1, amp: 0.6, heavy: 0, color: PAL.ink });
      CA.speck(c, x, y, 7, 900 + k, v);
    } else {
      const w = (along - 1) / 0.3, lx = 540 + S.side * (120 + 90 * hs(k, 2)), ly = 1000 + 140 * hs(k, 3);
      CA.speck(c, lerp(540, lx, E.out2(w)), lerp(880, ly, E.out2(w)), 7, 900 + k, v);
    }
  });
  c.restore();
  // labels: clear of the airway, above y 1250
  sticker(c, 'BIG BITS: STUCK IN THE NOSE', 740, 430, tq, MK('nose') - 0.05, MK('eyes') - 0.15, v, { size: 26, fill: PAL.hi, color: PAL.navy, rot: -0.03, seed: 4101 });
  sticker(c, 'TINY BITS: DEEP IN THE LUNGS', 740, 520, tq, MK('lungs'), MK('eyes') - 0.15, v, { size: 26, rot: 0.03, seed: 4102 });
  if (tq >= MK('tiny') && tq < MK('nose') - 0.05) sticker(c, 'PM2.5', 760, 470, tq, MK('tiny'), MK('nose') - 0.05, v, { size: 46, rot: -0.04, seed: 4103 });
  sticker(c, 'EYES', 800, 440, tq, MK('eyes'), endOf(2), v, { size: 40, rot: -0.04, seed: 4104 });
  sticker(c, 'NOSE', 830, 540, tq, MK('nose2'), endOf(2), v, { size: 40, rot: 0.04, seed: 4105 });
  sticker(c, 'BREATHING', 790, 640, tq, MK('breathing'), endOf(2), v, { size: 40, rot: -0.03, seed: 4106 });
}
