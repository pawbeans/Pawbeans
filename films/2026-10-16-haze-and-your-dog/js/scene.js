// ------------------------------------------------------------------ frame
function shotAt(t) {
  if (t < 6.5) return shotWindow;
  if (t < 14.0) return shotInside;
  if (t < 22.0) return shotSigns;
  if (t < 26.0) return shotRisk;
  if (t < 31.0) return shotTips;
  if (t < 37.0) return shotBig;
  if (t < 40.0) return shotVet;
  if (t < 44.5) return shotGame;
  if (t < 48.0) return shotPouch;
  if (t < XEND) return shotQuestion;
  return shotEnd;
}
const LAYER = { c: null };
function layer() {
  if (!LAYER.c) { const cv = document.createElement('canvas'); cv.width = W * DPR; cv.height = H * DPR; LAYER.c = cv.getContext('2d'); }
  const L = LAYER.c; L.setTransform(1, 0, 0, 1, 0, 0); L.clearRect(0, 0, W * DPR, H * DPR); L.setTransform(DPR, 0, 0, DPR, 0, 0);
  L.fillStyle = PAL.cream; L.fillRect(0, 0, W, H); return L;
}
export function render(t) {
  const fn = Math.min(NF - 1, Math.max(0, Math.round(t * FPS)));
  const D = { ...drawing(fn), fn }, tn = fn / FPS, v = bv(D);
  const t1 = toOld(tn), f = Math.round(t1 * FPS);
  const c = ctx;
  c.setTransform(DPR, 0, 0, DPR, 0, 0); c.globalAlpha = 1; c.globalCompositeOperation = 'source-over';
  c.fillStyle = PAL.cream; c.fillRect(0, 0, W, H); // fresh page every frame: no stale pixels
  const wb = WHIPS.find((b) => t1 >= b - WH && t1 < b + WH);
  if (wb !== undefined) { // whip pan: out to the left, in from the right, the middle frames smeared wide, speed lines
    const k = (t1 - (wb - WH)) / (2 * WH), first = k < 0.5;
    const L = layer();
    const D2 = { ...D, fq: Math.round((first ? wb - 0.05 : wb + 0.01) * FPS), fn: FF(first ? wb - 0.05 : wb + 0.01) };
    (first ? shotAt(wb - 0.01) : shotAt(wb + 0.01))(L, t1, f, D2);
    const dx = first ? -W * 0.55 * E.in2(k / 0.5) : W * 0.55 * (1 - E.out2((k - 0.5) / 0.5)), sx = 1 + 1.3 * Math.sin(Math.PI * k);
    c.save(); c.setTransform(1, 0, 0, 1, 0, 0); c.translate((W / 2 + dx) * DPR, 0); c.scale(sx, 1); c.drawImage(L.canvas, -W / 2 * DPR, 0); c.restore();
    for (let i = 0; i < 9; i++) { const y = 360 + i * 120 + hs(i, fn) * 40, x0 = hs(i, fn, 2) * 500; inkStroke(c, [[x0, y], [x0 + 420 + 200 * hs(i, 3), y + 6]], { seed: 900 + i + fn, w: 5, t0: 30, t1: 30, min: 0.1, amp: 0.6, heavy: 0 }); }
  } else if (IRISES.some(([b]) => t1 >= b - IW && t1 < b + IW)) { // iris: the next shot grows from where the eye is
    const [b, cx, cy] = IRISES.find(([b]) => t1 >= b - IW && t1 < b + IW), u = (t1 - (b - IW)) / (2 * IW), R = 40 + 2200 * E.in2(u);
    shotAt(b - 0.01)(c, t1, f, { ...D, fq: Math.round((b - IW) * FPS), fn: FF(b - IW) });
    const L = layer(); shotAt(b + 0.01)(L, t1, f, { ...D, fq: Math.round((b + 0.01) * FPS), fn: FF(b + 0.01) });
    c.save(); c.beginPath(); c.arc(cx, cy, R, 0, Math.PI * 2); c.clip(); c.setTransform(1, 0, 0, 1, 0, 0); c.drawImage(L.canvas, 0, 0); c.restore();
    inkLoop(c, circlePts(cx, cy, R, 60), { seed: 950 + fn, w: 10, amp: 2 });
  } else if (t1 >= XEND && t1 < XEND + XD) { // a fresh sheet slides over from the right on 1s: hard edge, no ghosts
    shotQuestion(c, t1, f, D);
    const L = layer(); shotEnd(L, t1, f, D);
    const xw = W * (1 - E.out2((t1 - XEND + 1 / FPS) / XD));
    c.save(); c.beginPath(); c.rect(xw, 0, W - xw, H); c.clip(); c.setTransform(1, 0, 0, 1, 0, 0); c.drawImage(L.canvas, 0, 0); c.restore();
    if (xw > 8) inkStroke(c, [[xw, -20], [xw + 6, H / 2], [xw, H + 20]], { seed: 960 + fn, w: 6, t0: 4, t1: 4, min: 0.4, amp: 1.2, heavy: 0 });
  } else shotAt(t1)(c, t1, f, D);
  const hk = fn - FF(HERO);
  if (hk === 1 || hk === 2) { // impact: flat Rabbit + a cream star, on 1s; nothing else on it
    FX.impactFrame(c, W, H, CA.WIN.x1 - 30, 915, hk === 1 ? RAB : PAL.navy, hk === 1 ? PAL.hi : RAB, 600 + hk, { lines: hk === 1, R: 560 });
    drawTooth(c, W, H, v, DPR, 0.13); return;
  }
  overlays(c, tn, t1, v);
  drawTooth(c, W, H, v, DPR, 0.13);
  if (t1 >= XEND + XD) drawLogo(c, 0); // a still, clean logo above the grain
}
