function warp(t, from, to) {
  const A = TL.warp;
  if (t <= A[0][from]) return A[0][to];
  for (let i = 1; i < A.length; i++) if (t <= A[i][from]) { const [p, q] = [A[i - 1], A[i]]; return p[to] + (q[to] - p[to]) * (t - p[from]) / ((q[from] - p[from]) || 1); }
  return A[A.length - 1][to];
}
